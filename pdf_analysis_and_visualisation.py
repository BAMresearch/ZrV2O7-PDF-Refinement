    def plot_overview(self, output_dir="analysis_plots"):
        """
        Generates a comprehensive suite of graphical summaries depicting the 
        extracted refinement data.
        
        Args:
            output_dir (str): The target directory for the generated visualisations.
        """
        if not os.path.exists(output_dir):
            os.makedirs(output_dir)
            
        df = pd.DataFrame(self.summary_data)
        
        if df.empty:
            print("[WARN] No analytical data was extracted for visualisation.")
            return
            
        df = df.sort_values('Temperature')

        # 1. Refinement Residual (Rw) vs Temperature
        plt.figure(figsize=(7, 5))
        sns.lineplot(data=df, x='Temperature', y='Final_Rw', marker='o', color='firebrick')
        plt.title("Final Fit Quality vs Temperature")
        plt.xlabel("Temperature (°C)")
        plt.ylabel("Rw")
        plt.grid(True, alpha=0.3)
        plt.savefig(os.path.join(output_dir, "1_Rw_vs_Temp.png"), dpi=300)
        plt.close()

        # 2. Lattice Parameter vs Temperature
        plt.figure(figsize=(7, 5))
        sns.lineplot(data=df, x='Temperature', y='a', marker='s', color='navy')
        plt.title("Lattice Parameter 'a' vs Temperature")
        plt.xlabel("Temperature (°C)")
        plt.ylabel("Lattice Constant a (Å)")
        plt.grid(True, alpha=0.3)
        plt.savefig(os.path.join(output_dir, "2_Lattice_vs_Temp.png"), dpi=300)
        plt.close()
        
        # 3. Structural Forensics: Bonding Anomalies vs Temperature
        plt.figure(figsize=(7, 5))
        sns.barplot(data=df, x='Temperature', y='VO_Outlier_Pct', color='teal')
        plt.title("Percentage of V-O Bond Outliers (> 1.8 Å)")
        plt.xlabel("Temperature (°C)")
        plt.ylabel("Outliers (%)")
        plt.xticks(rotation=45)
        plt.tight_layout()
        plt.savefig(os.path.join(output_dir, "3_Forensics_Outliers.png"), dpi=300)
        plt.close()

        # 3b. Mean Transversal Displacement vs Temperature
        if 'Mean_U_tra_V-O-V' in df.columns and 'Mean_U_tra_Zr-O-V' in df.columns:
            plt.figure(figsize=(7, 5))
            sns.lineplot(data=df, x='Temperature', y='Mean_U_tra_V-O-V', marker='o', label='V-O-V')
            sns.lineplot(data=df, x='Temperature', y='Mean_U_tra_Zr-O-V', marker='s', label='Zr-O-V')
            plt.title("Mean Transversal Displacement ($U_{tra}$) vs Temperature")
            plt.xlabel("Temperature (°C)")
            plt.ylabel("$U_{tra}$ (Å)")
            plt.legend()
            plt.grid(True, alpha=0.3)
            plt.savefig(os.path.join(output_dir, "3b_Utra_vs_Temp.png"), dpi=300)
            plt.close()

        # 3c. Full Transversal Displacement KDE Distributions
        self._plot_utra_distributions(output_dir)

        # 3d. Full Angle KDE Distributions
        self._plot_angle_distributions(output_dir)

        # 4. Refinement Residual Convergence Profile
        self._plot_convergence_history(output_dir)
        
        # 5. Detailed Bonding Forensics Distribution
        self._plot_forensics_evolution(output_dir)

        # 6. Specific Parameter Evolution Arrays
        self._plot_params_evolution(output_dir, df)
        
        # 7. Compile Final Analytical Dataframe
        df.to_csv(os.path.join(output_dir, "summary_table.csv"), index=False)
        
        # 8. Save Raw Distribution Data for Replotting
        self._save_distribution_data(output_dir)
        
        print(f"[INFO] Analytical compilation complete. Outputs saved securely within '{output_dir}/'.")

    def _save_distribution_data(self, output_dir):
        """
        Saves the raw array data for transversal displacements and bond angles 
        into CSV files to allow for external replotting.
        """
        for bond_type, dists in self.utra_distributions.items():
            if not dists: continue
            max_len = max([len(arr) for arr in dists.values()] + [0])
            padded_data = {}
            for temp in sorted(dists.keys()):
                arr = dists[temp]
                padded_arr = np.pad(arr, (0, max_len - len(arr)), constant_values=np.nan)
                padded_data[f"{temp}C"] = padded_arr
            pd.DataFrame(padded_data).to_csv(os.path.join(output_dir, f"7_Utra_Data_{bond_type}.csv"), index=False)

        for bond_type, dists in self.angle_distributions.items():
            if not dists: continue
            max_len = max([len(arr) for arr in dists.values()] + [0])
            padded_data = {}
            for temp in sorted(dists.keys()):
                arr = dists[temp]
                padded_arr = np.pad(arr, (0, max_len - len(arr)), constant_values=np.nan)
                padded_data[f"{temp}C"] = padded_arr
            pd.DataFrame(padded_data).to_csv(os.path.join(output_dir, f"8_Angle_Data_{bond_type}.csv"), index=False)

    def _plot_utra_distributions(self, output_dir):
        """
        Generates overlaid Kernel Density Estimate (KDE) distributions of the 
        transversal displacements across all temperatures, mapping the density evolution.
        """
        for bond_type, dists in self.utra_distributions.items():
            if not dists:
                continue
            
            plt.figure(figsize=(8, 6))
            temps = sorted(dists.keys())
            if not temps:
                continue
                
            norm = plt.Normalize(min(temps), max(temps))
            cmap = plt.cm.viridis_r
            
            for temp in temps:
                u_tra = dists[temp]
                if len(u_tra) > 0:
                    sns.kdeplot(u_tra, fill=True, color=cmap(norm(temp)), alpha=0.3, linewidth=1.5)
            
            sm = plt.cm.ScalarMappable(cmap=cmap, norm=norm)
            sm.set_array([])
            cbar = plt.colorbar(sm, ax=plt.gca())
            cbar.set_label('Temperature (°C)')
            
            plt.xlabel(rf"U$_{{tra}}$ ($\AA$)", fontsize=14)
            plt.ylabel("Density", fontsize=14)
            plt.tick_params(axis='both', labelsize=12, length=6, width=1.5)
            plt.title(f"Transversal Displacement ($U_{{tra}}$) Density - {bond_type}")
            plt.tight_layout()
