    def _plot_params_evolution(self, output_dir, df):
        """
        Generates a multi-panel grid charting the progressive evolution of targeted 
        refinement variables against temperature. Dynamically calibrates the y-axis 
        to ensure data trends remain prominent, disregarding excessive calculated 
        uncertainties.
        """
        params_to_plot = self.target_params
        
        fig, axes = plt.subplots(2, 3, figsize=(18, 10))
        axes = axes.flatten()
        
        for i, param in enumerate(params_to_plot):
            ax = axes[i]
            
            if param in df.columns:
                x = df['Temperature']
                y = df[param]
                y_err = df[f"{param}_err"]
                
                ax.errorbar(x, y, yerr=y_err, fmt='-o', capsize=2, markersize=5, 
                            color='darkcyan', ecolor='gray', alpha=0.8)
                
                ax.set_title(param)
                ax.set_xlabel('Temperature (°C)')
                ax.set_ylabel('Refined Value')
                
                valid_y = y[~np.isnan(y)]
                if len(valid_y) > 0:
                    y_min, y_max = np.min(valid_y), np.max(valid_y)
                    
                    if y_min == y_max:
                        margin = abs(y_min) * 0.1 if y_min != 0 else 0.1
                    else:
                        margin = (y_max - y_min) * 0.1
                        
                    ax.set_ylim(y_min - margin, y_max + margin)
                
                ax.grid(True, alpha=0.3)
            else:
                ax.text(0.5, 0.5, f"Parameter '{param}' Unidentified", ha='center')

        plt.tight_layout()
        plt.suptitle("Refinement Variable Evolution Sequences (Auto-Scaled Y-Axes)", y=1.02, fontsize=16)
        plt.savefig(os.path.join(output_dir, "6_Parameters_Evolution.png"), dpi=300, bbox_inches='tight')
        plt.close()

