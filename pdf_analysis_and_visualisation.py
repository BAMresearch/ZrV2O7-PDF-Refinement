class GeometricBondAnalyzer:
    """
    Analyses geometric structural properties, including bond distances, angles,
    and transversal displacements, from CIF structural models utilising the pymatgen library.
    
    Transversal displacement (U_tra) measures the orthogonal distance of a central 
    bridging atom (e.g., oxygen) away from the linear axis connecting its two 
    adjacent metal neighbours. It effectively quantifies the degree of non-linearity 
    or "buckling" within an atomic linkage.
    
    Derived from the original experimental bond analysis workflow by Joana Bustamante.
    """
    def __init__(self, rcut=2.5):
        """
        Initialises the GeometricBondAnalyzer.
        
        Args:
            rcut (float): The maximum cutoff radius (in Ångströms) for identifying adjacent atomic neighbours.
        """
        self.rcut = rcut

    def extract_angles(self, cif_path, center_species, neigh1, neigh2):
        """
        Extracts bond lengths and corresponding angles for a specified atomic triad within the structure.
        
        Args:
            cif_path (str): The file pathway to the target CIF structural model.
            center_species (str): The elemental symbol of the central atom within the triad.
            neigh1 (str): The elemental symbol of the first neighbouring atom.
            neigh2 (str): The elemental symbol of the second neighbouring atom.
            
        Returns:
            dict: A dictionary containing arrays of the first bond lengths ('D1'), 
                  the second bond lengths ('D2'), and the subtended angles ('Angle').
        """
        d1 = []
        d2 = []
        angles = []
        try:
            import warnings
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                struc = Structure.from_file(cif_path)
        except Exception as e:
            print(f"[WARN] GeometricBondAnalyzer failed to load {cif_path}: {e}")
            return {'D1': d1, 'D2': d2, 'Angle': angles}

        center_indices = [i for i, site in enumerate(struc.sites) if site.species_string == center_species]
        
        for ix in center_indices:
            center_site = struc[ix]
            neighbors = struc.get_neighbors(center_site, self.rcut)
            neighbors = [n for n in neighbors if n.species_string in (neigh1, neigh2)]
            
            for j, k in combinations(neighbors, 2):
                if ((j.species_string == neigh1 and k.species_string == neigh2) or
                    (j.species_string == neigh2 and k.species_string == neigh1)):
        
                    vec1 = j.coords - center_site.coords
                    vec2 = k.coords - center_site.coords
                   
                    d1.append(np.linalg.norm(vec1))
                    d2.append(np.linalg.norm(vec2))
                    angles.append(get_angle(vec1, vec2))

        return {'D1': d1, 'D2': d2, 'Angle': angles}

    def calculate_transversal_displacement(self, d1_array, d2_array, angle_array):
        """
        Computes the transversal displacement (U_tra) of the central bridging atom. 
        This parameter represents the perpendicular offset (buckling) of the central atom 
        relative to the direct vector connecting its two adjacent neighbours, utilising 
        trigonometric principles (Law of Cosines and Sines).
        
        Args:
            d1_array (list or np.ndarray): An array of the first bond distances.
            d2_array (list or np.ndarray): An array of the second bond distances.
            angle_array (list or np.ndarray): An array of the internal angles (in degrees) 
                                              subtended by the two bonds.
            
        Returns:
            np.ndarray: An array containing the calculated transversal displacements in Ångströms.
        """
        if not d1_array:
            return np.array([])
            
        d1 = np.array(d1_array)
        d2 = np.array(d2_array)
        ang = np.array(angle_array) * np.pi / 180  # radians

        c = np.sqrt(d1**2 + d2**2 - 2 * d1 * d2 * np.cos(ang))
        with np.errstate(divide='ignore', invalid='ignore'):
            sin_term = (d1 * np.sin(ang)) / c
            sin_term = np.clip(sin_term, -1.0, 1.0)
            B = np.arcsin(sin_term) * 180 / np.pi
            theta = 180 - np.array(angle_array) - B

        u_tra = d2 * np.sin(theta * np.pi / 180)
        return u_tra

    def process_structure(self, cif_path):
        """
        Executes a comprehensive geometric analysis of a given structural model, 
        evaluating predefined atomic triads to determine bond angles and transversal 
        displacements.
        
        Args:
            cif_path (str): The file pathway to the target CIF structural model.
            
        Returns:
            tuple: A tuple containing two dictionaries. The first dictionary holds the 
                   extracted geometric data for each triad. The second dictionary contains 
                   the calculated transversal displacement statistics for relevant bonds.
        """
        triads = [
            ("V", "O", "O", "O-V-O"),
            ("Zr", "O", "O", "O-Zr-O"),
            ("O", "V", "V", "V-O-V"),
            ("O", "Zr", "V", "Zr-O-V")
        ]
        
        results = {}
        for center, n1, n2, name in triads:
            results[name] = self.extract_angles(cif_path, center, n1, n2)
            
        u_tra_results = {}
        for mom_bond in ["V-O-V", "Zr-O-V"]:
            if mom_bond in results and len(results[mom_bond]['Angle']) > 0:
                u_tra = self.calculate_transversal_displacement(
                    results[mom_bond]['D1'],
                    results[mom_bond]['D2'],
                    results[mom_bond]['Angle']
                )
                u_tra_results[mom_bond] = {
                    'U_tra_mean': float(np.nanmean(u_tra)) if u_tra.size > 0 else np.nan,
                    'U_tra_values': u_tra
                }
            else:
                u_tra_results[mom_bond] = {
                    'U_tra_mean': np.nan,
                    'U_tra_values': np.array([])
                }
                
        return results, u_tra_results

