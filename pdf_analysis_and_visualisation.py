class ResultsAggregator:
    """
    Aggregates analytical results and structural parameters from multiple 
    refinement directories. Facilitates the extraction, compilation, and 
    visualisation of sequential refinement trends.
    """
    
    def __init__(self, fit_root_dir, config_dict):
        """
        Initialises the ResultsAggregator.
        
        Args:
            fit_root_dir (str): The primary directory pathway containing the 
                                sequential refinement dataset subdirectories.
            config_dict (dict): The central project configuration dictionary.
        """
        self.root_dir = fit_root_dir
        self.config = RefinementConfig(config_dict)
        self.analyzer = StructureAnalyzer(self.config.detailed_composition)
        self.bond_analyzer = GeometricBondAnalyzer(rcut=2.5)
        
        self.summary_data = []
        self.rw_histories = {} # Dictionary mapping temperature to its corresponding DataFrame
        self.detailed_forensics_data = [] # List storing dictionaries of individual bond parameters
        self.utra_distributions = {'V-O-V': {}, 'Zr-O-V': {}} # Stores transversal displacement arrays for KDE generation
        self.angle_distributions = {'O-V-O': {}, 'O-Zr-O': {}, 'V-O-V': {}, 'Zr-O-V': {}} # Stores bond angle arrays for KDE generation
        
        # Defining the targeted subset of refinement parameters for explicit extraction
        self.target_params = [
            'Uiso_O_Phase0', 'Uiso_V_Phase0', 'Uiso_Zr_Phase0',
            'delta2_Phase0', 'psize_Phase0', 's_Phase0'
        ]

    def parse_temperature(self, folder_name):
        """
        Extracts the numeric temperature value from a formatted directory string.
        
        Args:
            folder_name (str): The name of the dataset subdirectory.
            
        Returns:
            int or None: The extracted temperature integer, or None if unmatched.
        """
        match = re.search(r'_(\d+)C_', folder_name)
        if match:
            return int(match.group(1))
        return None

    def scan_and_extract(self):
        """
        Systematically scans the target directory to parse subdirectories and 
        extract refinement quality metrics (Rw), lattice dimensions, specific 
        refinement parameters, and structural bonding forensics.
        """
        print(f"[INFO] Scanning refinement results within: {self.root_dir}")
        
        try:
            subdirs = sorted([d for d in os.listdir(self.root_dir) 
                              if os.path.isdir(os.path.join(self.root_dir, d))])
        except FileNotFoundError:
            print(f"[ERROR] The specified directory pathway was not found: {self.root_dir}")
            return

        with concurrent.futures.ProcessPoolExecutor() as executor:
            results = list(executor.map(self._process_single_folder, subdirs))

        for res in results:
            if res is None:
                continue
                
            temp, record, history_df, forensics_list, utra_data_out, angle_data_out = res
            
            self.summary_data.append(record)
            if not history_df.empty:
                self.rw_histories[temp] = history_df
            self.detailed_forensics_data.extend(forensics_list)
            
            if utra_data_out['V-O-V'] is not None:
                self.utra_distributions['V-O-V'][temp] = utra_data_out['V-O-V']
            if utra_data_out['Zr-O-V'] is not None:
                self.utra_distributions['Zr-O-V'][temp] = utra_data_out['Zr-O-V']
                
            for triad, angles in angle_data_out.items():
                if angles is not None:
                    self.angle_distributions[triad][temp] = angles
                    
            print(f"  > Processed Sequence {temp}°C | Final Rw: {record['Final_Rw']:.4f} | Lattice a: {record['a']:.3f}")

    def _process_single_folder(self, folder):
        """
        Worker function to process a single temperature dataset directory.
        Returns aggregated structural and parameter records to be integrated.
        """
        temp = self.parse_temperature(folder)
        if temp is None:
            return None
        
        full_path = os.path.join(self.root_dir, folder)
        
        # 1. Extract Refinement Residual (Rw) History
        history_df = self._stitch_rw_logs(full_path)
        final_rw = history_df['Rw'].iloc[-1] if not history_df.empty else np.nan

        # 2. Extract Structural Dimensions & Bonding Forensics
        cif_path = os.path.join(full_path, "Phase0_2.cif")
        structure_stats = {'a': np.nan, 'vol': np.nan, 'outlier_pct': 0}
        forensics_list = []
        utra_data_out = {'V-O-V': None, 'Zr-O-V': None}
        angle_data_out = {'O-V-O': None, 'O-Zr-O': None, 'V-O-V': None, 'Zr-O-V': None}
        
        if os.path.exists(cif_path):
            try:
                stru = loadStructure(cif_path)
                structure_stats['a'] = stru.lattice.a
                structure_stats['vol'] = stru.lattice.volume
                
                forensics_stats, forensics_list = self._run_forensics(cif_path, temp)
                structure_stats.update(forensics_stats)
                
                bond_data, utra_data = self.bond_analyzer.process_structure(cif_path)
                structure_stats['Mean_U_tra_V-O-V'] = utra_data['V-O-V']['U_tra_mean']
                structure_stats['Mean_U_tra_Zr-O-V'] = utra_data['Zr-O-V']['U_tra_mean']
                
                utra_data_out['V-O-V'] = utra_data['V-O-V']['U_tra_values']
                utra_data_out['Zr-O-V'] = utra_data['Zr-O-V']['U_tra_values']
                
                for triad in angle_data_out.keys():
                    if triad in bond_data:
                        angle_data_out[triad] = bond_data[triad]['Angle']
            except Exception as e:
                print(f"[WARN] Failed to parse the CIF model for {temp}°C. Error: {e}")

        # 3. Extract Specific Refinement Parameters
        summary_path = os.path.join(full_path, "fitting_summary_2.txt")
        param_stats = self._extract_params_from_summary(summary_path)

        # Compile standard record format
        record = {
            'Temperature': temp,
            'Path': full_path,
            'Final_Rw': final_rw,
            **structure_stats,
            **param_stats
        }
        
        return (temp, record, history_df, forensics_list, utra_data_out, angle_data_out)

    def _stitch_rw_logs(self, folder_path):
        """
        Aggregates sequential refinement residual logs to construct a continuous, 
        global iteration axis for tracking convergence.
        
        Args:
            folder_path (str): The specific subdirectory path containing the logs.
            
        Returns:
            pd.DataFrame: The aggregated history of the refinement sequence.
        """
        log_files = sorted(glob.glob(os.path.join(folder_path, "rw_log_*.csv")))
        dfs = []
        cumulative_iter = 0
        
        for log in log_files:
            try:
                df = pd.read_csv(log)
                df['Global_Iteration'] = df['Iteration'] + cumulative_iter
                dfs.append(df)
                if not df.empty:
                    cumulative_iter = df['Global_Iteration'].iloc[-1]
            except pd.errors.EmptyDataError:
                pass
            except Exception as e:
                print(f"[WARN] Encountered an error processing {log}: {e}")
                
        if dfs:
            return pd.concat(dfs, ignore_index=True)
        return pd.DataFrame()

    def _run_forensics(self, cif_path, temp):
        """
        Utilises the StructureAnalyzer to systematically identify anomalous bond 
        distances (outliers) and categorise their local connectivity topologies.
        
        Args:
            cif_path (str): The pathway to the relevant CIF structural model.
            temp (int): The associated dataset temperature.
            
        Returns:
            dict: Compiled summary statistics relating to bonding configurations.
        """
        wrapper = _ForensicsWrapper(loadStructure(cif_path))
        all_bonds = self.analyzer.get_polyhedral_bond_vectors(wrapper)
        
        oxygen_connectivity = {}
        for b_type, bonds in all_bonds.items():
            if 'O-O' in b_type:
                continue 
            for bond in bonds:
                o_idx = bond['atom2']['index']
                cation_sym = bond['central_atom']['symbol']
                oxygen_connectivity.setdefault(o_idx, []).append(cation_sym)

        def get_conn_type(bond):
            o_idx = bond['atom2']['index']
            vertex_sym = bond['atom2']['symbol']
            cats = oxygen_connectivity.get(o_idx, [])
            
            if not cats:
                return "Isolated"
                
            unique_cats = sorted(list(set(cats)))
            if len(cats) == 1:
                return f"Terminal ({cats[0]}-{vertex_sym})"
            elif len(unique_cats) == 1:
                return f"Bridge ({unique_cats[0]}-{vertex_sym}-{unique_cats[0]})"
            else:
                return f"Linker ({'-'.join(unique_cats)})"

        target_bonds = all_bonds.get('V-O', [])
        if not target_bonds:
            return {}, []
        
        total = len(target_bonds)
        outliers = [b for b in target_bonds if b['length'] > 1.80] 
        
        forensics_list = []
        for bond in target_bonds:
            forensics_list.append({
                'Temperature': temp,
                'Bond_Length': bond['length'],
                'Connectivity': get_conn_type(bond),
                'Is_Outlier': bond['length'] > 1.80
            })

        stats = {
            'VO_Total': total,
            'VO_Outliers': len(outliers),
            'VO_Outlier_Pct': (len(outliers) / total) * 100 if total else 0
        }
        return stats, forensics_list

    def _extract_params_from_summary(self, summary_path):
        """
        Parses the refinement summary text document to extract targeted variables 
        and their associated mathematical uncertainties.
        
        Args:
            summary_path (str): The pathway to the relevant summary text file.
            
        Returns:
            dict: The extracted parameters mapped to their values and errors.
        """
        extracted = {}
        for p in self.target_params:
            extracted[p] = np.nan
            extracted[f"{p}_err"] = np.nan

        if not os.path.exists(summary_path):
            return extracted

        try:
            with open(summary_path, 'r') as f:
                lines = f.readlines()
            
            for line in lines:
                parts = line.strip().split()
                if not parts:
                    continue
                
                param_name = parts[0]
                if param_name in self.target_params:
                    try:
                        extracted[param_name] = float(parts[1])
                        
                        if len(parts) >= 4 and parts[2] == '+/-':
                            extracted[f"{param_name}_err"] = float(parts[3])
                        else:
                            extracted[f"{param_name}_err"] = 0.0
                    except ValueError:
                        pass
        except Exception as e:
            print(f"[WARN] Error extracting parameters from {summary_path}. Error: {e}")
            
        return extracted

